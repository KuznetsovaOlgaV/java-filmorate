create table if not exists mpa_ratings (
    mpa_id int primary key,
    name varchar(50) not null unique,
    description varchar(255)
);

create table if not exists genres (
    genre_id int primary key,
    name varchar(50) not null unique
);

create table if not exists films (
    film_id BIGINT generated by default as identity primary key,
    name varchar(255) not null,
    description TEXT,
    release_date date not null,
    duration int not null,
    mpa_rating_id int not null,
    constraint fk_films_mpa foreign key (mpa_rating_id) references mpa_ratings(mpa_id)
);

create table if not exists film_genres (
    film_id BIGINT not null,
    genre_id int not null,
    primary key (film_id, genre_id),
    constraint fk_film_genres_film foreign key (film_id) references films(film_id) on delete cascade,
    constraint fk_film_genres_genre foreign key (genre_id) references genres(genre_id) on delete cascade
);

create table if not exists users (
    user_id BIGINT generated by default as identity primary key,
    email varchar(255) not null unique,
    login varchar(50) not null unique,
    name varchar(255),
    birthday date not null
);

create table if not exists likes (
    film_id BIGINT not null,
    user_id BIGINT not null,
    primary key (film_id, user_id),
    constraint fk_likes_film foreign key (film_id) references films(film_id) on delete cascade,
    constraint fk_likes_user foreign key (user_id) references users(user_id) on delete cascade
);

create table if not exists friendship_status (
    status_id int primary key,
    name varchar(50) not null unique
);

create table if not exists friends (
    user_id BIGINT not null,
    friend_id BIGINT not null,
    status_id int not null,
    primary key (user_id, friend_id),
    check (user_id <> friend_id),
    constraint fk_friends_user foreign key (user_id) references users(user_id) on delete cascade,
    constraint fk_friends_friend foreign key (friend_id) references users(user_id) on delete cascade,
    constraint fk_friends_status foreign key (status_id) references friendship_status(status_id) on delete RESTRICT
);

create table if not exists directors (
    director_id BIGINT generated by default as identity primary key,
    name varchar(255) not null
);

create table if not exists film_directors (
    film_id BIGINT not null,
    director_id BIGINT not null,
    primary key (film_id, director_id),
    constraint fk_film_directors_film foreign key (film_id) references films(film_id) on delete cascade,
    constraint fk_film_directors_director foreign key (director_id) references directors(director_id) on delete cascade
);

create table if not exists reviews (
    review_id BIGINT generated by default as identity primary key,
    content varchar(1000) not null,
    is_positive BOOLEAN not null,
    user_id BIGINT not null references users (user_id),
    film_id BIGINT not null references films (film_id),
    useful int default 0
);

create table if not exists review_marks (
    review_id BIGINT not null,
    user_id BIGINT not null,
    constraint fk_review_marks_review foreign key (review_id) references reviews(review_id) on delete cascade,
    constraint fk_review_marks_user foreign key (user_id) references users(user_id),
    is_like BOOLEAN not null, -- true = лайк, false = дизлайк
    primary key (review_id, user_id)
    constraint fk_friends_user
        foreign key (user_id)
        references users(user_id)
        on delete cascade,
    constraint fk_friends_friend
        foreign key (friend_id)
        references users(user_id)
        on delete cascade,
    constraint fk_friends_status
        foreign key (status_id)
        references friendship_status(status_id)
        on delete RESTRICT
    constraint fk_friends_user foreign key (user_id) references users(user_id) on delete cascade,
    constraint fk_friends_friend foreign key (friend_id) references users(user_id) on delete cascade,
    constraint fk_friends_status foreign key (status_id) references friendship_status(status_id) on delete RESTRICT
);

create table if not exists directors (
    director_id BIGINT generated by default as identity primary key,
    name varchar(255) not null
);

create table if not exists film_directors (
    film_id BIGINT not null,
    director_id BIGINT not null,
    primary key (film_id, director_id),
    constraint fk_film_directors_film foreign key (film_id) references films(film_id) on delete cascade,
    constraint fk_film_directors_director foreign key (director_id) references directors(director_id) on delete cascade
);

create table if not exists reviews (
    review_id BIGINT generated by default as identity primary key,
    content varchar(1000) not null,
    is_positive BOOLEAN not null,
    user_id BIGINT not null references users (user_id),
    film_id BIGINT not null references films (film_id),
    useful int default 0
);

create table if not exists review_marks (
    review_id BIGINT not null,
    user_id BIGINT not null,
    constraint fk_review_marks_review foreign key (review_id) references reviews(review_id) on delete cascade,
    constraint fk_review_marks_user foreign key (user_id) references users(user_id),
    is_like BOOLEAN not null, -- true = лайк, false = дизлайк
    primary key (review_id, user_id)
);

create table if not exists events (
    event_id BIGINT generated by default as identity primary key,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    event_type varchar(50) not null,
    operation varchar(50) not null,
    user_id BIGINT not null,
    entity_user_id BIGINT,
    entity_film_id BIGINT,
    entity_review_id BIGINT,
    constraint fk_user
        foreign key (user_id)
        references users(user_id)
        on delete cascade,
    constraint fk_entity_user
            foreign key (entity_user_id)
            references users(user_id)
            on delete cascade,
    constraint fk_entity_film
                foreign key (entity_film_id)
                references films(film_id)
                on delete cascade,
    constraint fk_entity_review
                    foreign key (entity_review_id)
                    references reviews(review_id)
                    on delete cascade
);